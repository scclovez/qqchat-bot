# -*- coding: utf-8 -*-
"""陪学关系策略：让学习能力服务于女友关系，而不是反过来。

本模块只做轻量、无状态的判断与内部提示，不生成最终 QQ 文案，也不写数据库。
学习引擎仍负责题目、判分与进度；这里负责先识别此刻是否适合继续学习。
"""
from __future__ import annotations

from dataclasses import dataclass


PAUSE_WORDS = (
    "不想学", "不学了", "先不学", "暂停", "等会儿学", "晚点学", "不背了", "休息下",
    "好累", "太累", "累了", "好困", "困了", "烦死了", "有点烦", "今天算了",
    "改天", "明天再", "先聊会", "聊点别的", "我有事", "我先忙",
)
CHAT_WORDS = (
    "在干嘛", "你呢", "想你", "爱你", "哈哈", "嘿嘿", "吃饭", "睡觉", "打游戏",
    "今天", "刚刚", "学校", "上班", "上课", "朋友", "新闻", "照片", "看看",
)


@dataclass(frozen=True)
class PendingTurn:
    """学习中收到一条消息后的边界判断。"""

    kind: str  # answer / pause / chat
    reason: str


def classify_pending_turn(text: str) -> PendingTurn:
    """区分学习答案、暂停意图与正常聊天。

    不猜测用户是否答对；只把明显不是答案的内容从判分器前拦下。这样用户在
    学习途中说「今天好累」或「你在干嘛」时，仍能先得到一个女友的正常回应。
    """
    value = (text or "").strip()
    compact = value.replace(" ", "")
    if any(word in compact for word in PAUSE_WORDS):
        return PendingTurn("pause", "用户明确想暂停或状态不适合继续")
    if not compact:
        return PendingTurn("chat", "空消息不是学习作答")
    if "?" in compact or "？" in compact:
        return PendingTurn("chat", "用户正在正常提问")
    if any(word in compact for word in CHAT_WORDS):
        return PendingTurn("chat", "用户在发起日常聊天")
    # 答案可以是词、释义、拼写，也可以是「不知道」；不在这里做对错判断。
    return PendingTurn("answer", "像一次针对当前问题的回答")


