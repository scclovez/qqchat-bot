def learning_relationship_instruction(event: str) -> str:
    """返回仅供模型使用的关系约束；最终文案仍由现有人设链路生成。"""
    detail = _EVENTS.get(event, "根据他现在的状态，用女友的方式陪着他，不要抢走正常聊天。")
    return _BASE + "\n本次情境：" + detail


def fallback_reply(event: str) -> str:
    """模型不可用时也保持关系优先，避免兜底突然变成学习系统。"""
    return {
        "pause": "好，那先不学了，等你想继续再叫我",
        "correct": "这不就会嘛",
        "retry": "没事，再想一下",
        "explain": "卡这儿很正常，我陪你慢慢弄",
        "start": "好，今天我盯着你",
        "finish": "今天这几个我记着，下次还查你",
    }.get(event, "好呀，我陪你")
