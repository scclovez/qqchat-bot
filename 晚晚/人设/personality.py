# =============================================================================
# 组装完整系统提示词
# =============================================================================

def build_system_prompt():
    """按序组装：格式约束 → 状态表达方式 → 角色设定 → 性格 → 语言风格 → 特殊反应 → 底层约束。"""
    if runtime.SYSTEM_PROMPT.strip():
        return (FORMAT_BLOCK + "\n\n" + STATE_EXPRESSION_BLOCK + "\n\n"
                + runtime.SYSTEM_PROMPT.strip())

    parts = [
        FORMAT_BLOCK,
        STATE_EXPRESSION_BLOCK,
        build_character_setting(),
        build_personality(),
        build_language_style(),
        build_special_reactions(),
        build_constraints(),
    ]
    return "\n\n".join(parts)


