# =============================================================================
# 辅助函数
# =============================================================================

def _section(title, content):
    return f"## {title}\n{content}"


def _get(val, default):
    s = val.strip()
    return s if s else default


# =============================================================================
# 分模块构建
# =============================================================================

def build_character_setting():
    name = _get(runtime.GIRLFRIEND_NAME, "bot")
    age = _get(runtime.GIRLFRIEND_AGE, "22")
    birthdate = _get(runtime.GIRLFRIEND_BIRTHDATE, "")
    identity = _get(runtime.GIRLFRIEND_IDENTITY, "在读艺术系研究生，喜欢画画和摄影")
    scenario = _get(runtime.GIRLFRIEND_SCENARIO, DEFAULT_SCENARIO)
    appearance = _get(runtime.GIRLFRIEND_APPEARANCE, DEFAULT_APPEARANCE)
    birth_part = f"，{birthdate}出生" if birthdate else ""
    text = (f"你是{name}，{age}岁{birth_part}，{identity}。你正在和你的男朋友通过 QQ 聊天。\n\n"
            f"生活背景与常见习惯（不是实时位置，实时状态以连续生活状态为准）：{scenario}"
            f"\n\n你的外貌：{appearance}")
    return _section("角色设定", text)


def build_personality():
    text = _get(runtime.GIRLFRIEND_CHARACTER, DEFAULT_CHARACTER)
    return _section("性格", text)


def build_language_style():
    text = _get(runtime.GIRLFRIEND_LANGUAGE_STYLE, DEFAULT_LANGUAGE_STYLE)
    return _section("语言风格", text)


def build_special_reactions():
    text = _get(runtime.GIRLFRIEND_SPECIAL_REACTIONS, DEFAULT_SPECIAL_REACTIONS)
    return _section("特殊反应", text)


def build_constraints():
    text = _get(runtime.GIRLFRIEND_CONSTRAINTS, DEFAULT_CONSTRAINTS)
    return _section("底层约束", text)


